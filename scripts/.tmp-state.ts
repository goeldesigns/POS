import "dotenv/config";
import { prisma } from "../src/server/db";
const r = await prisma.restaurant.findFirstOrThrow({ where: { name: "Spice & Stone" } });
const open = await prisma.order.groupBy({ by: ["status", "type"], where: { restaurantId: r.id, status: { in: ["DRAFT","NEW","PREPARING","READY","SERVED"] } }, _count: true });
console.log("open", open);
const oldest = await prisma.order.findMany({ where: { restaurantId: r.id, status: { in: ["NEW","PREPARING","READY","SERVED"] } }, select: { orderNumber: true, status: true, type: true, placedAt: true, paymentStatus: true, table: { select: { name: true } } }, orderBy: { placedAt: "asc" } });
console.log(oldest);
const tables = await prisma.diningTable.groupBy({ by: ["status"], where: { restaurantId: r.id }, _count: true });
console.log("tables", tables);
const prods = await prisma.product.findMany({ where: { restaurantId: r.id, OR: [{ variants: { some: {} } }, { modifierGroups: { some: {} } }] }, select: { name: true, _count: { select: { variants: true, modifierGroups: true } } }, take: 20 });
console.log(prods);
const c = await prisma.customer.findMany({ where: { restaurantId: r.id }, select: { name: true, phone: true, loyaltyBalance: true }, take: 8, orderBy: { totalOrders: "desc" } });
console.log(c);
const last = await prisma.order.findFirst({ where: { restaurantId: r.id }, orderBy: { createdAt: "desc" }, select: { createdAt: true } });
console.log("last order", last);
await prisma.$disconnect();
