// ─── Database & server ──────────────────────────────────────────────────────

function videoDatabaseUrl() {
  const url = new URL(process.env.DATABASE_URL ?? "postgresql://postgres:postgres@localhost:5433/tabla_dev?schema=public");
  if (url.pathname.slice(1) === VIDEO_DB) throw new Error("DATABASE_URL already points at the video database");
  const admin = new URL(url);
  admin.pathname = "/postgres";
  admin.search = "";
  url.pathname = `/${VIDEO_DB}`;
  return { url: url.toString(), admin: admin.toString() };
}

function run(cmd: string, argv: string[], env: NodeJS.ProcessEnv) {
  const res = spawnSync(process.execPath, [cmd, ...argv], { env, stdio: ["ignore", "inherit", "inherit"] });
  if (res.status !== 0) throw new Error(`${path.basename(cmd)} ${argv.join(" ")} failed`);
}

/** Drop and reseed the throwaway video database, so timers and "today" read naturally. */
async function prepareDatabase(url: string, admin: string) {
  console.log(`Preparing ${VIDEO_DB} …`);
  const client = new pg.Client({ connectionString: admin });
  await client.connect();
  await client.query(`DROP DATABASE IF EXISTS ${VIDEO_DB} WITH (FORCE)`);
  await client.query(`CREATE DATABASE ${VIDEO_DB}`);
  await client.end();
  const env = { ...process.env, DATABASE_URL: url };
  run("node_modules/prisma/build/index.js", ["migrate", "deploy"], env);
  run("node_modules/tsx/dist/cli.mjs", ["prisma/seed.ts"], env);
}

async function startServer(url: string): Promise<ChildProcess> {
  if (!existsSync(".next/BUILD_ID")) throw new Error("No production build found. Run `npm run build` first.");
  const child = spawn(process.execPath, ["node_modules/next/dist/bin/next", "start", "-p", String(PORT)], {
    env: { ...process.env, DATABASE_URL: url, APP_URL: `http://localhost:${PORT}` },
    stdio: ["ignore", "ignore", "inherit"],
  });
  for (let i = 0; i < 120; i++) {
    await sleep(500);
    try {
      const res = await fetch(`http://localhost:${PORT}/auth/login`);
      if (res.ok) return child;
    } catch {
      // not up yet
    }
  }
  child.kill();
  throw new Error("Server did not start");
}

function stopServer(child: ChildProcess) {
  if (process.platform === "win32" && child.pid) spawnSync("taskkill", ["/pid", String(child.pid), "/T", "/F"], { stdio: "ignore" });
  else child.kill();
}

