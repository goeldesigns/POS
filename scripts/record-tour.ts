/**
 * Record the product tour video for the landing page.
 *
 *   public/landing/tour.mp4               1920×1080 H.264 + AAC, captions burned in
 *   public/landing/tour-poster.webp       still shown before playback
 *   src/components/landing/tour-chapters.ts   chapter start times for the player
 *
 * How it works: recreates a throwaway `tabla_video` database next to your dev
 * database (your dev data is never touched), seeds it so the service looks
 * live, serves the production build from it on :3100, then drives a headless
 * Chrome/Edge through every module with a visible cursor and captions. Frames
 * come from the DevTools screencast and are encoded with ffmpeg.
 *
 *   npm run build
 *   npm run video:tour
 *
 * Flags (for working on the script):
 *   --only=pos-dine-in,kitchen   record just these chapters (logs in first)
 *   --keep-db                    reuse the existing tabla_video data
 *   --base=http://localhost:3000 drive an already running server instead
 *   --shots                      also save a PNG at every caption (scratch/tour-shots)
 *   --no-video                   skip encoding
 *   --audio-only                 redo just the soundtrack on the existing video (no browser, no server)
 *   --music=path/to/track.mp3    use your own licensed track instead of the generated music
 *                                (TOUR_MUSIC_VOLUME, default 0.3); the UI sounds stay on top
 *
 * Sound: an original music bed generated by scripts/tour-audio.ts (nothing to
 * license) plus soft clicks, keystrokes and whooshes at the recorded moments,
 * normalised to about −18 LUFS.
 */
