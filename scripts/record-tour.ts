/** Redo only the soundtrack on the existing video, from the saved click/keystroke timings. */
function remixAudio() {
  if (!existsSync(EVENTS_FILE) || !existsSync(OUT_VIDEO)) throw new Error("Record the tour first: npm run video:tour");
  const { duration, events } = JSON.parse(readFileSync(EVENTS_FILE, "utf8")) as { duration: number; events: TourSoundEvent[] };
  const work = mkdtempSync(path.join(tmpdir(), "tabla-tour-"));
  try {
    const silent = path.join(work, "video.mp4");
    const res = spawnSync(ffmpegInstaller.path, ["-y", "-hide_banner", "-loglevel", "error", "-i", OUT_VIDEO, "-map", "0:v:0", "-c", "copy", silent], { stdio: "inherit" });
    if (res.status !== 0) throw new Error("ffmpeg could not read the video");
    addSoundtrack(silent, events, duration, work, OUT_VIDEO);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

async function main() {
  if (args.has("audio-only")) return remixAudio();
  const only = args.get("only")?.split(",");
  const chapters = only ? CHAPTERS.filter((c) => only.includes(c.key)) : CHAPTERS;
  if (only && chapters.length !== only.length) throw new Error(`Unknown chapter in --only. Known: ${CHAPTERS.map((c) => c.key).join(", ")}`);
  const full = !only;

  let server: ChildProcess | null = null;
  let base = args.get("base");
  if (!base) {
    const db = videoDatabaseUrl();
    if (!args.has("keep-db")) await prepareDatabase(db.url, db.admin);
    console.log(`Starting production server on :${PORT} …`);
    server = await startServer(db.url);
    base = `http://localhost:${PORT}`;
  }

  const exe = BROWSER_PATHS.find((p) => existsSync(p));
  if (!exe) throw new Error("No Chrome or Edge found. Set CHROME_PATH.");
  const browser = await chromium.launch({ executablePath: exe, headless: true, args: ["--hide-scrollbars", "--force-color-profile=srgb", "--mute-audio"] });
  const work = mkdtempSync(path.join(tmpdir(), "tabla-tour-"));
  try {
    const context = await browser.newContext({ viewport: VIEW, deviceScaleFactor: SCALE, locale: "en-IN", timezoneId: "Asia/Kolkata", colorScheme: "light" });
    // tsx keeps function names with an `__name` helper that doesn't exist in the page.
    await context.addInitScript({ content: `var __name = (f) => f;\n(${installOverlay.toString()})();` });
    const page = await context.newPage();
    page.setDefaultTimeout(20_000);
    const cdp = await context.newCDPSession(page);
    const rec = new Recorder(cdp, work);
    await rec.start();
    const tour = new Tour(page, rec, base, args.has("shots"));
    if (args.has("shots")) rmSync(SHOTS_DIR, { recursive: true, force: true });

    await page.goto(`${base}/auth/login`);
    await tour.settle(300);
    await page.mouse.move(tour.pos.x, tour.pos.y);

    if (!chapters.some((c) => c.key === "login")) {
      // Sign in off camera for partial runs.
      await page.fill("#email", OWNER.email);
      await page.fill("#password", OWNER.password);
      await page.getByRole("button", { name: "Sign in" }).click();
      await page.waitForURL(/\/app\//);
      await tour.settle(300);
    }

    if (full) await tour.card(INTRO);
    await rec.resume();
    if (full) {
      tour.sounds.push({ t: 0, type: "card-in" });
      await tour.wait(4600);
      await tour.card(null);
      await tour.wait(700);
    }

    for (const c of chapters) {
      console.log(`▸ ${c.key}`);
      await tour.chapter(c.key, c.title);
      try {
        await c.run(tour);
      } catch (error) {
        mkdirSync(SHOTS_DIR, { recursive: true });
        await page.screenshot({ path: path.join(SHOTS_DIR, `error-${c.key}.png`) }).catch(() => {});
        throw error;
      }
    }

    await tour.hideCaption();
    if (full) {
      await tour.wait(500);
      await tour.card(OUTRO);
      await tour.wait(4200);
    }
    await rec.stop();

    if (!args.has("no-video") && full) {
      const silent = path.join(work, "silent.mp4");
      encode(rec, work, silent);
      mkdirSync(path.dirname(EVENTS_FILE), { recursive: true });
      writeFileSync(EVENTS_FILE, JSON.stringify({ duration: rec.end, events: tour.sounds }));
      addSoundtrack(silent, tour.sounds, rec.end, work, OUT_VIDEO);
      spawnSync(ffmpegInstaller.path, ["-y", "-hide_banner", "-loglevel", "error", "-ss", tour.posterAt.toFixed(2), "-i", OUT_VIDEO, "-frames:v", "1", "-c:v", "libwebp", "-quality", "82", OUT_POSTER], { stdio: "inherit" });
      const chaptersOut = tour.chapters.map((c) => ({ ...c, start: Math.round(c.start * 10) / 10 }));
      writeFileSync(
        OUT_CHAPTERS,
        `// Generated by scripts/record-tour.ts — re-run \`npm run video:tour\` instead of editing.\n\nexport const TOUR_DURATION = ${Math.round(rec.end * 10) / 10};\n\nexport const TOUR_CHAPTERS: { key: string; title: string; start: number }[] = ${JSON.stringify(chaptersOut, null, 2)};\n`,
      );
      console.log(`✓ ${path.relative(process.cwd(), OUT_VIDEO)} (${rec.end.toFixed(1)}s, ${chaptersOut.length} chapters)`);
    } else if (!args.has("no-video")) {
      // Partial runs never touch the published video.
      mkdirSync(SHOTS_DIR, { recursive: true });
      const preview = path.join(SHOTS_DIR, "preview.mp4");
      const silent = path.join(work, "silent.mp4");
      encode(rec, work, silent);
      addSoundtrack(silent, tour.sounds, rec.end, work, preview);
      console.log(`Preview: ${path.relative(process.cwd(), preview)} (${rec.end.toFixed(1)}s)`);
    }
  } finally {
    await browser.close();
    rmSync(work, { recursive: true, force: true });
    if (server) stopServer(server);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
