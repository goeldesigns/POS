// ─── Screencast recorder ────────────────────────────────────────────────────

class Recorder {
  frames: { file: string; t: number }[] = [];
  private paused = true;
  private pausedAt = 0;
  private offset = 0;
  private t0: number | null = null;
  private n = 0;
  end = 0;

  constructor(private cdp: CDPSession, private dir: string) {}

  async start() {
    this.cdp.on("Page.screencastFrame", ({ data, metadata, sessionId }) => {
      void this.cdp.send("Page.screencastFrameAck", { sessionId }).catch(() => {});
      if (!this.paused) this.push(data, metadata.timestamp ?? Date.now() / 1000);
    });
    await this.cdp.send("Page.startScreencast", { format: "jpeg", quality: 92, maxWidth: 1920, maxHeight: 1080, everyNthFrame: 1 });
  }

  private push(data: string, ts: number) {
    const t = ts - this.offset;
    if (this.t0 == null) this.t0 = t;
    const file = path.join(this.dir, `${String(this.n++).padStart(6, "0")}.jpg`);
    writeFileSync(file, Buffer.from(data, "base64"));
    const last = this.frames.at(-1)?.t ?? 0;
    this.frames.push({ file, t: Math.max(t - this.t0, last) });
  }

  /** Seconds into the finished video. */
  now() {
    if (this.t0 == null) return 0;
    return (this.paused ? this.pausedAt : Date.now() / 1000) - this.offset - this.t0;
  }

  get recording() {
    return !this.paused;
  }

  pause() {
    if (this.paused) return;
    this.paused = true;
    this.pausedAt = Date.now() / 1000;
  }

  async resume() {
    if (!this.paused) return;
    const now = Date.now() / 1000;
    if (this.pausedAt) this.offset += now - this.pausedAt;
    this.paused = false;
    // The screencast only sends frames on change: grab the current screen so the cut is clean.
    const { data } = await this.cdp.send("Page.captureScreenshot", { format: "jpeg", quality: 92 });
    this.push(data, now);
  }

  async stop() {
    this.end = this.now();
    this.pause();
    await this.cdp.send("Page.stopScreencast").catch(() => {});
  }
}

function encode(rec: Recorder, workDir: string, out: string) {
  const ffmpeg = ffmpegInstaller.path;
  const list = [`ffconcat version 1.0`];
  rec.frames.forEach((f, i) => {
    const next = rec.frames[i + 1]?.t ?? rec.end;
    list.push(`file '${f.file.replace(/\\/g, "/")}'`, `duration ${Math.max(next - f.t, 0.001).toFixed(4)}`);
  });
  list.push(`file '${rec.frames.at(-1)!.file.replace(/\\/g, "/")}'`);
  const listFile = path.join(workDir, "frames.txt");
  writeFileSync(listFile, list.join("\n"));
  console.log(`Encoding ${rec.frames.length} frames, ${rec.end.toFixed(1)}s …`);
  const res = spawnSync(
    ffmpeg,
    [
      "-y", "-hide_banner", "-loglevel", "error",
      "-f", "concat", "-safe", "0", "-i", listFile,
      "-vf", "fps=30,scale=1920:1080:flags=lanczos,format=yuv420p",
      "-c:v", "libx264", "-preset", "slow", "-crf", "21", "-tune", "animation",
      "-movflags", "+faststart", "-an",
      out,
    ],
    { stdio: "inherit" },
  );
  if (res.status !== 0) throw new Error("ffmpeg failed");
}

function loudness(file: string) {
  const res = spawnSync(ffmpegInstaller.path, ["-hide_banner", "-i", file, "-af", "ebur128", "-f", "null", "-"], { encoding: "utf8" });
  // The summary at the end: "I: -20.2 LUFS" followed by its threshold line.
  const match = /I:\s+(-?[\d.]+) LUFS\s*\n\s*Threshold/.exec(res.stderr ?? "");
  return match ? Number(match[1]) : TARGET_LUFS;
}

/**
 * Build the soundtrack (generated music, or --music=<file> under the UI sounds),
 * bring it to ~−18 LUFS and put it on the video. The video stream is copied untouched.
 */
function addSoundtrack(silentVideo: string, events: TourSoundEvent[], duration: number, workDir: string, out: string) {
  const ffmpeg = ffmpegInstaller.path;
  const music = args.get("music");
  const wav = path.join(workDir, "soundtrack.wav");
  const info = renderTourAudio({ duration, events, outFile: wav, music: !music });
  let mix = wav;
  if (music) {
    if (!existsSync(music)) throw new Error(`Music file not found: ${music}`);
    mix = path.join(workDir, "mixed.wav");
    const volume = Number(process.env.TOUR_MUSIC_VOLUME ?? 0.3);
    const res = spawnSync(
      ffmpeg,
      [
        "-y", "-hide_banner", "-loglevel", "error", "-i", wav, "-stream_loop", "-1", "-i", music,
        "-filter_complex", `[1:a]atrim=0:${duration.toFixed(2)},afade=t=in:d=1.5,afade=t=out:st=${(duration - 3).toFixed(2)}:d=3,volume=${volume},aresample=48000[m];[0:a][m]amix=inputs=2:duration=first:dropout_transition=0,volume=2[a]`,
        "-map", "[a]", "-ar", "48000", mix,
      ],
      { stdio: "inherit" },
    );
    if (res.status !== 0) throw new Error("ffmpeg could not mix the music file");
  }
  const gain = Math.min(TARGET_LUFS - loudness(mix), -1 - Number(info.peakDb));
  const tmp = `${out}.tmp.mp4`;
  const res = spawnSync(
    ffmpeg,
    [
      "-y", "-hide_banner", "-loglevel", "error", "-i", silentVideo, "-i", mix,
      "-map", "0:v:0", "-map", "1:a:0", "-c:v", "copy",
      "-af", `volume=${gain.toFixed(2)}dB`, "-c:a", "aac", "-b:a", "160k", "-ar", "48000",
      "-shortest", "-movflags", "+faststart", tmp,
    ],
    { stdio: "inherit" },
  );
  if (res.status !== 0) throw new Error("ffmpeg could not add the soundtrack");
  renameSync(tmp, out);
  console.log(`Soundtrack: ${music ? path.basename(music) : "generated music"} + UI sounds, ${gain >= 0 ? "+" : ""}${gain.toFixed(1)} dB to ~${TARGET_LUFS} LUFS`, info.levels);
}

// ─── Human-paced driving ────────────────────────────────────────────────────

type Box = { x: number; y: number; width: number; height: number };
type Chapter = { key: string; title: string; run: (t: Tour) => Promise<void> };

class Tour {
  pos = { x: VIEW.width / 2, y: VIEW.height / 2 };
  chapters: { key: string; title: string; start: number }[] = [];
  num = 0;
  /** Video time of the still used as the poster. */
  posterAt = 0;
  /** Clicks, keystrokes and transitions on the video timeline, for the sound effects. */
  sounds: TourSoundEvent[] = [];
  private shot = 0;

  constructor(
    readonly page: Page,
    readonly rec: Recorder,
    readonly base: string,
    private shots: boolean,
  ) {}

  wait(ms: number) {
    return sleep(ms);
  }

  async moveTo(x: number, y: number, ms?: number) {
    const from = { ...this.pos };
    const dist = Math.hypot(x - from.x, y - from.y);
    if (dist < 1) return;
    const duration = ms ?? Math.min(950, Math.max(320, 260 + dist * 0.55));
    const steps = Math.max(8, Math.round(duration / 16));
    // A slight arc reads as a hand, not a robot.
    const bend = Math.min(60, dist * 0.08) * (x > from.x ? -1 : 1);
    const start = Date.now();
    for (let i = 1; i <= steps; i++) {
      const t = i / steps;
      const e = t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2;
      const arc = Math.sin(Math.PI * t) * bend;
      const nx = from.x + (x - from.x) * e + ((y - from.y) / (dist || 1)) * arc;
      const ny = from.y + (y - from.y) * e - ((x - from.x) / (dist || 1)) * arc;
      await this.page.mouse.move(nx, ny);
      const due = start + duration * t;
      const left = due - Date.now();
      if (left > 0) await sleep(left);
    }
    this.pos = { x, y };
  }

  /** Scroll the element into view smoothly (only if needed) and return its box. */
  async reveal(loc: Locator): Promise<Box> {
    await loc.waitFor({ state: "visible", timeout: 20_000 });
    const inView = await loc.evaluate((el) => {
      const r = el.getBoundingClientRect();
      return r.top >= 64 && r.bottom <= innerHeight - 96 && r.left >= 0 && r.right <= innerWidth;
    });
    if (!inView) {
      await loc.evaluate((el) => el.scrollIntoView({ behavior: "smooth", block: "center", inline: "nearest" }));
      await sleep(800);
    }
    const box = await loc.boundingBox();
    if (!box) throw new Error(`No box for ${loc}`);
    return box;
  }

  async hover(loc: Locator, opts: { fx?: number; fy?: number; wait?: number } = {}) {
    const box = await this.reveal(loc);
    await this.moveTo(box.x + box.width * (opts.fx ?? 0.5), box.y + box.height * (opts.fy ?? 0.5));
    await this.wait(opts.wait ?? 400);
    return box;
  }

  sound(type: TourSoundEvent["type"]) {
    if (this.rec.recording) this.sounds.push({ t: Math.round(this.rec.now() * 1000) / 1000, type });
  }

  async click(loc: Locator, opts: { fx?: number; fy?: number; wait?: number } = {}) {
    await this.hover(loc, { ...opts, wait: 110 });
    this.sound("click");
    await this.page.mouse.down();
    await sleep(80);
    await this.page.mouse.up();
    await this.wait(opts.wait ?? 550);
  }

  async type(text: string, delay = 60) {
    for (const ch of text) {
      this.sound("key");
      await this.page.keyboard.type(ch);
      await sleep(delay * (0.55 + Math.random() * 0.9));
    }
  }

  async fill(loc: Locator, text: string, opts: { delay?: number; wait?: number } = {}) {
    await this.click(loc, { wait: 160 });
    await this.type(text, opts.delay);
    await this.wait(opts.wait ?? 350);
  }

  async select(loc: Locator, value: string | { label: string }, wait = 500) {
    await this.hover(loc, { wait: 150 });
    this.sound("click");
    await this.page.mouse.down();
    await sleep(80);
    await this.page.mouse.up();
    await loc.selectOption(value);
    await this.wait(wait);
  }

  async press(key: string, wait = 400) {
    this.sound("key");
    await this.page.keyboard.press(key);
    await this.wait(wait);
  }

  /** Smooth wheel scroll of whatever is under the cursor. */
  async scroll(dy: number, opts: { ms?: number; at?: { x: number; y: number } } = {}) {
    if (opts.at) await this.moveTo(opts.at.x, opts.at.y);
    const ms = opts.ms ?? Math.min(1400, 500 + Math.abs(dy) * 0.9);
    const steps = Math.round(ms / 16);
    let done = 0;
    for (let i = 1; i <= steps; i++) {
      const t = i / steps;
      const e = t < 0.5 ? 2 * t * t : 1 - Math.pow(-2 * t + 2, 2) / 2;
      const target = Math.round(dy * e);
      await this.page.mouse.wheel(0, target - done);
      done = target;
      await sleep(16);
    }
    await this.wait(350);
  }

  async chapter(key: string, title: string) {
    this.num++;
    this.chapters.push({ key, title, start: Math.max(0, this.rec.now()) });
    if (this.num > 1) this.sound("chapter");
    // Don't carry the last chapter's caption into the next screen.
    await this.hideCaption();
  }

  async say(title: string, text = "", opts: { pos?: "center" | "left" | "right"; hold?: number } = {}) {
    const num = String(this.num).padStart(2, "0");
    await this.page.evaluate((cap) => (window as unknown as { __tour: { caption: (c: unknown) => void } }).__tour.caption(cap), { num, title, text, pos: opts.pos });
    await this.wait(opts.hold ?? 1600);
    if (this.shots) {
      mkdirSync(SHOTS_DIR, { recursive: true });
      await this.page.screenshot({ path: path.join(SHOTS_DIR, `${String(++this.shot).padStart(3, "0")}-${this.chapters.at(-1)?.key ?? "x"}.png`) });
    }
  }

  markPoster() {
    this.posterAt = this.rec.now();
  }

  async hideCaption() {
    await this.page.evaluate(() => (window as unknown as { __tour: { caption: (c: unknown) => void } }).__tour.caption(null));
  }

  async spot(loc: Locator | null, pad = 8) {
    let rect = null;
    if (loc) {
      const b = await this.reveal(loc);
      rect = { x: b.x - pad, y: b.y - pad, w: b.width + pad * 2, h: b.height + pad * 2 };
    }
    await this.page.evaluate((r) => (window as unknown as { __tour: { spot: (r: unknown) => void } }).__tour.spot(r), rect);
  }

  async card(c: { kicker: string; title: string; text: string; chips?: string[] } | null) {
    this.sound(c ? "card-in" : "card-out");
    await this.page.evaluate((x) => (window as unknown as { __tour: { card: (c: unknown) => void } }).__tour.card(x), c);
  }

  /** Sidebar navigation, then wait for the page heading. */
  async nav(label: string, heading: string | RegExp = label) {
    await this.click(this.page.getByRole("navigation", { name: "Main" }).getByRole("link", { name: new RegExp(`^${label}`) }), { wait: 200 });
    await this.page.getByRole("heading", { level: 1, name: heading }).first().waitFor({ timeout: 20_000 });
    await this.settle();
  }

  /** Let images, charts and fonts finish so the frame looks done. */
  async settle(ms = 700) {
    await this.page.waitForLoadState("networkidle", { timeout: 8_000 }).catch(() => {});
    await this.page
      .evaluate(() =>
        Promise.race([
          Promise.all([...document.images].filter((i) => !i.complete).map((i) => new Promise((r) => ((i.onload = r), (i.onerror = r))))),
          new Promise((r) => setTimeout(r, 4000)),
        ]),
      )
      .catch(() => {});
    await this.wait(ms);
  }

  /** Do something off camera (navigation, waiting on data) and cut straight to the result. */
  async offCamera(fn: () => Promise<void>) {
    const was = this.rec.recording;
    this.rec.pause();
    await fn();
    if (was) await this.rec.resume();
  }

  dialog() {
    return this.page.getByRole("dialog").last();
  }

  /** A button, tab or segmented-control option by its label. */
  ctl(name: string | RegExp, scope: Page | Locator = this.page) {
    const opt = typeof name === "string" ? { name, exact: true } : { name };
    return scope.getByRole("button", opt).or(scope.getByRole("tab", opt)).or(scope.getByRole("radio", opt)).or(scope.getByRole("link", opt)).first();
  }
}

